package model;

public class SparePart1 {
	private int id;
	private String name;
	private String type;
	private String brand;
	private String origin;
	private float sellingPrice;
	private int stock;
	private String image;
	private String description;
	private int warrantyPeriod;

	public int getId() { return id; }
	public void setId(int id) { this.id = id; }
	public String getName() { return name; }
	public void setName(String name) { this.name = name; }
	public String getType() { return type; }
	public void setType(String type) { this.type = type; }
	public String getBrand() { return brand; }
	public void setBrand(String brand) { this.brand = brand; }
	public String getOrigin() { return origin; }
	public void setOrigin(String origin) { this.origin = origin; }
	public float getSellingPrice() { return sellingPrice; }
	public void setSellingPrice(float sellingPrice) { this.sellingPrice = sellingPrice; }
	public int getStock() { return stock; }
	public void setStock(int stock) { this.stock = stock; }
	public String getImage() { return image; }
	public void setImage(String image) { this.image = image; }
	public String getDescription() { return description; }
	public void setDescription(String description) { this.description = description; }
	public int getWarrantyPeriod() { return warrantyPeriod; }
	public void setWarrantyPeriod(int warrantyPeriod) { this.warrantyPeriod = warrantyPeriod; }
}
